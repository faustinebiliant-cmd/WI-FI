import React, { useState, useEffect } from 'react';
import apiClient from '../api/client';
import Loader from '../shared/components/Loader';

export default function RoutersPage() {
  const [routers, setRouters] = useState([]);
  const [loading, setLoading] = useState(true);
  const [showModal, setShowModal] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');
  
  // Zero-Touch Setup State
  const [showSetupModal, setShowSetupModal] = useState(false);
  const [setupToken, setSetupToken] = useState('');
  const [copied, setCopied] = useState(false);

  const [formData, setFormData] = useState({
    name: '',
    location_label: '',
    ip_address: '',
    api_username: '',
    api_password: ''
  });

  useEffect(() => { fetchRouters(); }, []);

  const fetchRouters = async () => {
    try {
      const res = await apiClient.get('/tenant/routers');
      setRouters(res.data.data);
    } catch (error) {
      console.error(error);
    } finally {
      setLoading(false);
    }
  };

  const handleCreate = async (e) => {
    e.preventDefault();
    setErrorMsg('');
    try {
      await apiClient.post('/tenant/routers', formData);
      setShowModal(false);
      setFormData({ name: '', location_label: '', ip_address: '', api_username: '', api_password: '' });
      fetchRouters();
    } catch (error) {
      setErrorMsg(error.response?.data?.error || 'Failed to create router');
    }
  };

  const startZeroTouchSetup = async () => {
    try {
      // Generate a random 12-character token
      const token = Math.random().toString(36).substring(2, 14);
      
      // Create the router record with this token
      await apiClient.post('/tenant/routers', {
        name: 'Auto-Provisioned Router',
        location_label: 'Waiting for connection',
        ip_address: '0.0.0.0',
        api_username: 'wifiapi',
        api_password: 'AutoGenerated123!',
        provision_token: token
      });
      
      setSetupToken(token);
      setShowSetupModal(true);
      fetchRouters();
    } catch (error) {
      alert('Failed to start setup. Make sure the backend supports provision_token.');
    }
  };

  const copyToClipboard = () => {
    const command = `/tool fetch url="https://oswagolink.co.tz/api/provision/bootstrap/${setupToken}" dst-path=bootstrap.rsc; /import bootstrap.rsc; /file remove bootstrap.rsc`;
    navigator.clipboard.writeText(command);
    setCopied(true);
    setTimeout(() => setCopied(false), 3000);
  };

  return (
    <div style={{ maxWidth: '1200px', margin: '0 auto' }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-end', flexWrap: 'wrap', gap: '16px', marginBottom: '30px' }}>
        <div>
          <h1 style={{ margin: 0 }}>Routers</h1>
          <p style={{ margin: '5px 0 0 0', color: '#6b7280' }}>Manage your MikroTik hardware.</p>
        </div>
        <div style={{ display: 'flex', gap: '10px' }}>
          <button onClick={() => setShowModal(true)} style={{ padding: '8px 16px', cursor: 'pointer', backgroundColor: '#e5e7eb', color: 'var(--dark)', border: 'none', borderRadius: '4px', fontWeight: 'bold' }}>
            Manual Setup
          </button>
          <button onClick={startZeroTouchSetup} style={{ padding: '8px 16px', cursor: 'pointer', backgroundColor: '#2563eb', color: 'white', border: 'none', borderRadius: '4px', fontWeight: 'bold' }}>
            + Add Auto-Router
          </button>
        </div>
      </div>

      <div style={{ backgroundColor: 'white', borderRadius: '8px', border: '1px solid #e5e7eb', overflowX: 'auto', WebkitOverflowScrolling: 'touch' }}>
        {loading ? (
          <Loader message="Loading routers..." />
        ) : routers.length === 0 ? (
          <div style={{ padding: '40px', textAlign: 'center' }}>No routers found. Add one to start selling WiFi.</div>
        ) : (
          <table style={{ width: 'max-content', minWidth: '100%', borderCollapse: 'collapse', textAlign: 'left' }}>
            <thead style={{ backgroundColor: '#f9fafb', borderBottom: '1px solid #e5e7eb' }}>
              <tr>
                <th style={{ padding: '12px 20px', color: '#6b7280', whiteSpace: 'nowrap' }}>Name</th>
                <th style={{ padding: '12px 20px', color: '#6b7280', whiteSpace: 'nowrap' }}>Status</th>
                <th style={{ padding: '12px 20px', color: '#6b7280', whiteSpace: 'nowrap' }}>IP Address</th>
              </tr>
            </thead>
            <tbody>
              {routers.map((router) => {
                const statusText = (router.status || 'offline').trim().toLowerCase();
                const isOnline = statusText === 'online';

                return (
                  <tr key={router.id} style={{ borderBottom: '1px solid #f3f4f6' }}>
                    <td style={{ padding: '16px 20px', fontWeight: 'bold', whiteSpace: 'nowrap' }}>{router.name}</td>
                    <td style={{ padding: '16px 20px', whiteSpace: 'nowrap' }}>
                      <span style={{ padding: '4px 10px', borderRadius: '50px', fontSize: '12px', fontWeight: 'bold', backgroundColor: isOnline ? '#ecfdf5' : '#fef2f2', color: isOnline ? '#059669' : '#dc2626' }}>
                        {statusText.toUpperCase()}
                      </span>
                    </td>
                    <td style={{ padding: '16px 20px', whiteSpace: 'nowrap' }}>{router.ip_address}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        )}
      </div>

      {/* MANUAL SETUP MODAL */}
      {showModal && (
        <div className="modal-overlay">
          <div className="modal-content">
            <h2 style={{ marginTop: 0 }}>Add New Router (Manual)</h2>
            {errorMsg && <div style={{ color: 'var(--danger)', backgroundColor: 'var(--danger-soft)', padding: '10px', borderRadius: '6px', marginBottom: '15px', fontSize: '13px' }}>{errorMsg}</div>}
            <form onSubmit={handleCreate} style={{ display: 'flex', flexDirection: 'column', gap: '15px' }}>
              <input required type="text" placeholder="Router Name" value={formData.name} onChange={e => setFormData({...formData, name: e.target.value})} style={{ padding: '10px' }} />
              <input type="text" placeholder="Location" value={formData.location_label} onChange={e => setFormData({...formData, location_label: e.target.value})} style={{ padding: '10px' }} />
              <input required type="text" placeholder="IP Address (10.20.0.x)" value={formData.ip_address} onChange={e => setFormData({...formData, ip_address: e.target.value})} style={{ padding: '10px' }} />
              <input required type="text" placeholder="API Username" value={formData.api_username} onChange={e => setFormData({...formData, api_username: e.target.value})} style={{ padding: '10px' }} />
              <input required type="password" placeholder="API Password" value={formData.api_password} onChange={e => setFormData({...formData, api_password: e.target.value})} style={{ padding: '10px' }} />
              
              <div style={{ display: 'flex', gap: '10px', justifyContent: 'flex-end', marginTop: '10px' }}>
                <button type="button" onClick={() => setShowModal(false)} style={{ padding: '10px 20px', cursor: 'pointer', backgroundColor: '#e5e7eb', border: 'none', borderRadius: '4px' }}>Cancel</button>
                <button type="submit" style={{ padding: '10px 20px', cursor: 'pointer', backgroundColor: '#2563eb', color: 'white', border: 'none', borderRadius: '4px', fontWeight: 'bold' }}>Save Router</button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* ZERO-TOUCH SETUP MODAL */}
      {showSetupModal && (
        <div className="modal-overlay">
          <div className="modal-content" style={{ maxWidth: '700px' }}>
            <h2 style={{ marginTop: 0, display: 'flex', alignItems: 'center', gap: '10px' }}>
              <span style={{ fontSize: '24px' }}>📡</span> Add a MikroTik
            </h2>
            <p style={{ color: 'var(--gray)', marginBottom: '20px' }}>
              Paste one command in the MikroTik terminal. The router builds the hotspot itself and registers on this account.
            </p>

            <div style={{ backgroundColor: '#fef3c7', border: '1px solid #f59e0b', padding: '15px', borderRadius: '6px', marginBottom: '20px' }}>
              <p style={{ color: '#92400e', fontWeight: 'bold', marginBottom: '8px', fontSize: '14px' }}>Step 1: Enable Advanced Mode (RouterOS 7.13+)</p>
              <code style={{ display: 'block', backgroundColor: 'white', padding: '10px', borderRadius: '4px', color: '#0f172a', fontSize: '13px', marginBottom: '8px' }}>
                /system/device-mode/update mode=advanced
              </code>
              <p style={{ color: '#92400e', fontSize: '12px', margin: 0 }}>
                If the router asks you to press a button, do it within 5 minutes, then continue.
              </p>
            </div>

            <div style={{ backgroundColor: '#eff6ff', border: '1px solid #bfdbfe', padding: '15px', borderRadius: '6px', marginBottom: '20px' }}>
              <p style={{ color: '#1e40af', fontWeight: 'bold', marginBottom: '8px', fontSize: '14px' }}>Step 2: Paste the Setup Command</p>
              <pre style={{ backgroundColor: 'white', padding: '15px', borderRadius: '4px', color: '#1e40af', whiteSpace: 'pre-wrap', wordBreak: 'break-all', fontSize: '12px', margin: 0 }}>
{`/tool fetch url="https://oswagolink.co.tz/api/provision/bootstrap/${setupToken}" dst-path=bootstrap.rsc; /import bootstrap.rsc; /file remove bootstrap.rsc`}
              </pre>
              <button 
                onClick={copyToClipboard}
                style={{ marginTop: '15px', width: '100%', padding: '12px', backgroundColor: copied ? '#10b981' : '#2563eb', color: 'white', border: 'none', borderRadius: '4px', fontWeight: 'bold', cursor: 'pointer', transition: 'all 0.2s' }}
              >
                {copied ? '✓ Copied to Clipboard!' : 'Copy Command'}
              </button>
            </div>

            <div style={{ display: 'flex', justifyContent: 'flex-end' }}>
              <button onClick={() => setShowSetupModal(false)} style={{ padding: '10px 20px', cursor: 'pointer', backgroundColor: '#e5e7eb', border: 'none', borderRadius: '4px', fontWeight: 'bold' }}>Close</button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}