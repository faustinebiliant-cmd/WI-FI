import React, { useState, useEffect } from 'react';
import apiClient from '../api/client';
import Loader from '../shared/components/Loader';

// Professional Copy Icon (SVG)
const CopyIcon = () => (
  <svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
    <rect x="9" y="9" width="13" height="13" rx="2" ry="2"></rect>
    <path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1"></path>
  </svg>
);

export default function RoutersPage() {
  const [routers, setRouters] = useState([]);
  const [loading, setLoading] = useState(true);
  const [showModal, setShowModal] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');
  
  // Zero-Touch Setup State
  const [showSetupModal, setShowSetupModal] = useState(false);
  const [setupToken, setSetupToken] = useState('');
  
  // Copy states
  const [copiedStep1, setCopiedStep1] = useState(false);
  const [copiedStep2, setCopiedStep2] = useState(false);

  // Strict Delete State
  const [deleteTarget, setDeleteTarget] = useState(null);
  const [deleteInput, setDeleteInput] = useState('');
  const [isDeleting, setIsDeleting] = useState(false);
  const [deleteError, setDeleteError] = useState('');

  const [formData, setFormData] = useState({ name: '', location_label: '' });

  useEffect(() => { fetchRouters(); }, []);

  const fetchRouters = async () => {
    try {
      const res = await apiClient.get('/tenant/routers');
      setRouters(res.data.data);
    } catch (error) {
      console.error(error);
    } finally {
      setLoading(false);
    }
  };

  const handleCreate = async (e) => {
    e.preventDefault();
    setErrorMsg('');
    try {
      const token = Math.random().toString(36).substring(2, 14);
      await apiClient.post('/tenant/routers', {
        name: formData.name,
        location_label: formData.location_label,
        ip_address: '0.0.0.0',
        api_username: 'wifiapi',
        api_password: 'AutoGenerated123!',
        provision_token: token
      });
      setSetupToken(token);
      setShowModal(false);
      setShowSetupModal(true);
      setFormData({ name: '', location_label: '' });
      fetchRouters();
    } catch (error) {
      setErrorMsg(error.response?.data?.error || 'Failed to create router');
    }
  };

  const handleDelete = async () => {
    if (deleteInput !== 'DELETE') return;
    setIsDeleting(true);
    try {
      await apiClient.delete(`/tenant/routers/${deleteTarget.id}`);
      setDeleteTarget(null);
      setDeleteInput('');
      fetchRouters();
    } catch (error) {
      setDeleteError('Failed to delete router');
    } finally {
      setIsDeleting(false);
    }
  };

  const step1Command = "/system/device-mode/update mode=advanced";
  const step2Command = `/tool fetch url="https://oswagolink.co.tz/api/provision/bootstrap/${setupToken}" dst-path=bootstrap.rsc; /import bootstrap.rsc; /file remove bootstrap.rsc`;

  const copyToClipboard = (text, step) => {
    navigator.clipboard.writeText(text);
    if (step === 1) { setCopiedStep1(true); setTimeout(() => setCopiedStep1(false), 2000); } 
    else { setCopiedStep2(true); setTimeout(() => setCopiedStep2(false), 2000); }
  };

  return (
    <div style={{ maxWidth: '1200px', margin: '0 auto', padding: '20px' }}>
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-end', flexWrap: 'wrap', gap: '16px', marginBottom: '30px' }}>
        <div>
          <h1 style={{ margin: 0 }}>Routers</h1>
          <p style={{ margin: '5px 0 0 0', color: '#6b7280' }}>Manage your MikroTik hardware.</p>
        </div>
        <button onClick={() => { setShowModal(true); setErrorMsg(''); }} style={{ padding: '8px 16px', cursor: 'pointer', backgroundColor: '#2563eb', color: 'white', border: 'none', borderRadius: '4px', fontWeight: 'bold' }}>
          + Add Router
        </button>
      </div>

      <div style={{ backgroundColor: 'white', borderRadius: '8px', border: '1px solid #e5e7eb', overflowX: 'auto' }}>
        {loading ? (
          <Loader message="Loading routers..." />
        ) : routers.length === 0 ? (
          <div style={{ padding: '40px', textAlign: 'center' }}>No routers found.</div>
        ) : (
          <table style={{ width: 'max-content', minWidth: '100%', borderCollapse: 'collapse', textAlign: 'left' }}>
            <thead style={{ backgroundColor: '#f9fafb', borderBottom: '1px solid #e5e7eb' }}>
              <tr>
                <th style={{ padding: '12px 20px', color: '#6b7280' }}>Name</th>
                <th style={{ padding: '12px 20px', color: '#6b7280' }}>Status</th>
                <th style={{ padding: '12px 20px', color: '#6b7280' }}>IP Address</th>
                <th style={{ padding: '12px 20px', color: '#6b7280' }}>Action</th>
              </tr>
            </thead>
            <tbody>
              {routers.map((router) => {
                const isOnline = (router.status || '').toLowerCase() === 'online';
                return (
                  <tr key={router.id} style={{ borderBottom: '1px solid #f3f4f6' }}>
                    <td style={{ padding: '16px 20px', fontWeight: 'bold' }}>{router.name}</td>
                    <td style={{ padding: '16px 20px' }}>
                      <span style={{ padding: '4px 10px', borderRadius: '50px', fontSize: '12px', fontWeight: 'bold', backgroundColor: isOnline ? '#ecfdf5' : '#fef2f2', color: isOnline ? '#059669' : '#dc2626' }}>
                        {isOnline ? 'ONLINE' : 'OFFLINE'}
                      </span>
                    </td>
                    <td style={{ padding: '16px 20px' }}>{router.ip_address}</td>
                    <td style={{ padding: '16px 20px' }}>
                      <button onClick={() => setDeleteTarget(router)} style={{ padding: '6px 12px', backgroundColor: '#fef2f2', color: '#dc2626', border: '1px solid #fecaca', borderRadius: '4px', cursor: 'pointer', fontWeight: 'bold' }}>
                        Delete
                      </button>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        )}
      </div>

      {/* CREATE ROUTER MODAL */}
      {showModal && (
        <div className="modal-overlay">
          <div className="modal-content">
            <h2 style={{ marginTop: 0 }}>Name Your Router</h2>
            <form onSubmit={handleCreate} style={{ display: 'flex', flexDirection: 'column', gap: '15px' }}>
              <input required type="text" placeholder="Router Name (e.g. Main Lobby)" value={formData.name} onChange={e => setFormData({...formData, name: e.target.value})} style={{ padding: '10px', border: '1px solid #ccc', borderRadius: '4px' }} />
              <input type="text" placeholder="Location (Optional)" value={formData.location_label} onChange={e => setFormData({...formData, location_label: e.target.value})} style={{ padding: '10px', border: '1px solid #ccc', borderRadius: '4px' }} />
              <div style={{ display: 'flex', gap: '10px', justifyContent: 'flex-end' }}>
                <button type="button" onClick={() => setShowModal(false)} style={{ padding: '10px 20px', backgroundColor: '#e5e7eb', border: 'none', borderRadius: '4px' }}>Cancel</button>
                <button type="submit" style={{ padding: '10px 20px', backgroundColor: '#2563eb', color: 'white', border: 'none', borderRadius: '4px', fontWeight: 'bold' }}>Generate</button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* ZERO-TOUCH SETUP MODAL */}
      {showSetupModal && (
        <div className="modal-overlay">
          <div className="modal-content" style={{ maxWidth: '700px', padding: '20px' }}>
            <h2 style={{ marginTop: 0, fontSize: '20px' }}>Connect Your MikroTik</h2>
            <p style={{ color: '#64748b', marginBottom: '20px', fontSize: '14px' }}>
              Paste one command in the MikroTik terminal. The router builds the hotspot itself and registers on this account.
            </p>

            {/* STEP 1 */}
            <div style={{ backgroundColor: '#fef3c7', border: '1px solid #f59e0b', padding: '15px', borderRadius: '6px', marginBottom: '20px' }}>
              <p style={{ color: '#92400e', fontWeight: 'bold', marginBottom: '8px', fontSize: '14px' }}>Step 1: Enable Advanced Mode</p>
              
              {/* RESPONSIVE CONTAINER */}
              <div style={{ display: 'flex', flexDirection: 'column', gap: '10px' }}>
                <code style={{ backgroundColor: 'white', padding: '10px', borderRadius: '4px', color: '#0f172a', fontSize: '12px', border: '1px solid #cbd5e1', wordBreak: 'break-all' }}>
                  {step1Command}
                </code>
                <button 
                  onClick={() => copyToClipboard(step1Command, 1)}
                  style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', gap: '8px', padding: '8px', backgroundColor: copiedStep1 ? '#10b981' : '#e2e8f0', color: copiedStep1 ? 'white' : '#334155', border: 'none', borderRadius: '4px', fontWeight: 'bold', cursor: 'pointer', transition: 'all 0.2s', fontSize: '13px' }}
                >
                  {copiedStep1 ? 'Copied!' : <><CopyIcon /> Copy Command</>}
                </button>
              </div>
            </div>

            {/* STEP 2 */}
            <div style={{ backgroundColor: '#eff6ff', border: '1px solid #bfdbfe', padding: '15px', borderRadius: '6px', marginBottom: '20px' }}>
              <p style={{ color: '#1e40af', fontWeight: 'bold', marginBottom: '8px', fontSize: '14px' }}>Step 2: Paste the Setup Command</p>
              
              {/* RESPONSIVE CONTAINER */}
              <div style={{ display: 'flex', flexDirection: 'column', gap: '10px' }}>
                <code style={{ backgroundColor: 'white', padding: '10px', borderRadius: '4px', color: '#1e40af', fontSize: '12px', border: '1px solid #cbd5e1', wordBreak: 'break-all' }}>
                  {step2Command}
                </code>
                <button 
                  onClick={() => copyToClipboard(step2Command, 2)}
                  style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', gap: '8px', padding: '8px', backgroundColor: copiedStep2 ? '#10b981' : '#2563eb', color: 'white', border: 'none', borderRadius: '4px', fontWeight: 'bold', cursor: 'pointer', transition: 'all 0.2s', fontSize: '13px' }}
                >
                  {copiedStep2 ? 'Copied!' : <><CopyIcon /> Copy Command</>}
                </button>
              </div>
            </div>

            <div style={{ display: 'flex', justifyContent: 'flex-end' }}>
              <button onClick={() => setShowSetupModal(false)} style={{ padding: '10px 20px', backgroundColor: '#e5e7eb', border: 'none', borderRadius: '4px', fontWeight: 'bold' }}>Close</button>
            </div>
          </div>
        </div>
      )}

      {/* STRICT DELETE ROUTER MODAL */}
      {deleteTarget && (
        <div className="modal-overlay">
          <div className="modal-content" style={{ maxWidth: '450px', borderTop: '4px solid #dc2626' }}>
            <h2 style={{ marginTop: 0, color: '#dc2626', fontSize: '20px' }}>Delete Router</h2>
            <p style={{ fontSize: '14px', marginBottom: '20px' }}>Are you sure you want to delete <strong>{deleteTarget.name}</strong>? This will delete all packages and vouchers.</p>
            <input type="text" placeholder="Type DELETE" value={deleteInput} onChange={e => setDeleteInput(e.target.value)} style={{ width: '100%', padding: '10px', border: '1px solid #ccc', borderRadius: '4px', marginBottom: '20px' }} />
            <div style={{ display: 'flex', gap: '10px', justifyContent: 'flex-end' }}>
              <button onClick={() => { setDeleteTarget(null); setDeleteInput(''); }} style={{ padding: '10px 20px', backgroundColor: '#e5e7eb', border: 'none', borderRadius: '4px' }}>Cancel</button>
              <button onClick={handleDelete} disabled={deleteInput !== 'DELETE' || isDeleting} style={{ padding: '10px 20px', backgroundColor: deleteInput === 'DELETE' ? '#dc2626' : '#fca5a5', color: 'white', border: 'none', borderRadius: '4px', fontWeight: 'bold' }}>
                {isDeleting ? 'Deleting...' : 'Delete'}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}