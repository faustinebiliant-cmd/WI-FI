const crypto = require('crypto');
const { execFile } = require('child_process');
const db = require('../config/db');
const { encrypt, decrypt } = require('../utils/encryption');

const TOKEN_RE = /^[A-Za-z0-9_-]{8,128}$/;
const PUBKEY_RE = /^[A-Za-z0-9+/]{43}=$/;
// Tunnel network 10.20.0.0/16 (about 65,000 addresses).
// 10.20.0.1 is the VPS and 10.20.0.2 the owner's own router; client routers
// start at 10.20.0.3. Addresses ending in .0 or .255 are never used.
// An address freed by a deleted router is handed out again, lowest first.
const TUNNEL_PREFIX = 16;
const TUNNEL_FIRST = 3;      // 10.20.0.3
const TUNNEL_LAST = 65534;   // 10.20.255.254

const tunnelIpFromIndex = (n) => `10.20.${Math.floor(n / 256)}.${n % 256}`;

// "10.20.X.Y" -> X*256+Y, anything else (other networks, hostnames, empty) -> null
const tunnelIndex = (ip) => {
  const m = /^10\.20\.(\d{1,3})\.(\d{1,3})$/.exec(String(ip || '').trim());
  if (!m) return null;
  const third = Number(m[1]);
  const fourth = Number(m[2]);
  if (third > 255 || fourth > 255) return null;
  return third * 256 + fourth;
};

const isClientTunnelIp = (ip) => {
  const n = tunnelIndex(ip);
  if (n === null || n % 256 === 0 || n % 256 === 255) return false;
  return n >= TUNNEL_FIRST && n <= TUNNEL_LAST;
};

// Gives a router its tunnel address: the lowest free one, one router at a time
const assignTunnelIp = async (routerId) => {
  const client = await db.pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(727001)');

    const cur = await client.query('SELECT tunnel_ip FROM routers WHERE id = $1', [routerId]);
    if (cur.rows[0] && cur.rows[0].tunnel_ip) {
      await client.query('COMMIT');
      return String(cur.rows[0].tunnel_ip);
    }

    // An address counts as taken if any router has it as tunnel_ip OR ip_address:
    // routers set up by hand before automation only have ip_address filled in
    const used = await client.query('SELECT tunnel_ip, ip_address FROM routers');
    const taken = new Set();
    for (const row of used.rows) {
      for (const addr of [row.tunnel_ip, row.ip_address]) {
        const n = tunnelIndex(addr);
        if (n !== null) taken.add(n);
      }
    }

    let next = null;
    for (let n = TUNNEL_FIRST; n <= TUNNEL_LAST; n++) {
      if (n % 256 === 0 || n % 256 === 255) continue;
      if (!taken.has(n)) { next = n; break; }
    }
    if (next === null) throw new Error('No free tunnel addresses left');

    const ip = tunnelIpFromIndex(next);
    await client.query('UPDATE routers SET tunnel_ip = $1, ip_address = $2 WHERE id = $3', [ip, ip, routerId]);
    await client.query('COMMIT');
    return ip;
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
};

const getBootstrapScript = async (req, res) => {
  try {
    const { token } = req.params;
    if (!TOKEN_RE.test(token)) return res.status(404).type('text/plain').send('# Invalid Token');

    const routerRes = await db.query('SELECT * FROM routers WHERE provision_token = $1', [token]);
    const router = routerRes.rows[0];
    if (!router) return res.status(404).type('text/plain').send('# Invalid Token');
    if (router.provisioned_at) return res.status(410).type('text/plain').send('# This token was already used');

    const assignedIp = await assignTunnelIp(router.id);

    // One API password per router, stored encrypted so the backend can log in
    let apiPassword = null;
    if (router.api_username === 'wifiapi' && router.api_password_encrypted) {
      try { apiPassword = decrypt(router.api_password_encrypted); } catch (e) { apiPassword = null; }
    }
    if (apiPassword === 'AutoGenerated123!') apiPassword = null;
    if (!apiPassword) {
      apiPassword = crypto.randomBytes(16).toString('hex');
      await db.query(
        'UPDATE routers SET api_username = $1, api_port = $2, api_password_encrypted = $3 WHERE id = $4',
        ['wifiapi', 8728, encrypt(apiPassword), router.id]
      );
    }

    // Speed profiles from 1 to 20 Mbps (the adapter also creates others on demand)
    let speedProfiles = '';
    for (let i = 1; i <= 20; i++) {
      const kbps = i * 1024;
      speedProfiles += '/ip hotspot user profile add name=spd-' + kbps + 'd-' + kbps + 'u rate-limit=' + kbps + 'k/' + kbps + 'k shared-users=1\n';
    }

    // NOTE: inside this template, a RouterOS backslash must be written as two (\\)
    const script = `
# ===== OSWAGOLINK AUTO-PROVISIONING =====
# Run ONLY on a factory-fresh router, after setting the admin password.
:if ([:len [/interface wireguard find name=wg-vps]] > 0) do={ :error "ALREADY PROVISIONED - this router is already set up. Nothing was changed." }
:if (![/system device-mode get scheduler]) do={ :error "SCHEDULER IS OFF - run: /system device-mode update scheduler=yes, then unplug and replug the power within 5 minutes, then run this setup again. Nothing was changed." }

/system identity set name=oswagolink-${assignedIp.replace(/\./g, '-')}
/system clock set time-zone-autodetect=no time-zone-name=Africa/Dar_es_Salaam
/ip dns set allow-remote-requests=yes servers=8.8.8.8,1.1.1.1
/ip cloud set update-time=yes
/system ntp client set enabled=yes servers=time.google.com,pool.ntp.org,time.cloudflare.com
/disk settings set auto-media-sharing=no auto-smb-sharing=no

/interface wireguard add name=wg-vps listen-port=51820 mtu=1420
/ip address add address=${assignedIp}/${TUNNEL_PREFIX} interface=wg-vps comment="VPS API tunnel"
/interface wireguard peers add interface=wg-vps name=peer1 public-key="ge0I3cNGfsm5MuItotNBt5KDrSGeg3lhRThsDFc3byY=" endpoint-address=69.62.105.119 endpoint-port=51820 allowed-address=10.20.0.1/32 persistent-keepalive=25s comment="WI-FI VPS"

/ip firewall filter add chain=input action=accept protocol=tcp dst-port=8728 in-interface=wg-vps src-address=10.20.0.1 place-before=0 comment="Allow VPS API through WireGuard"
/ip firewall filter add chain=forward action=drop src-address=192.168.88.0/24 out-interface=wg-vps place-before=0 comment="Guests cannot use VPS tunnel"

/ip hotspot profile set [find default=yes] login-by=http-pap
/ip hotspot profile add name=hsprof1 hotspot-address=192.168.88.1 html-directory=flash/hotspot login-by=http-pap
/ip hotspot add name=hotspot1 interface=bridge address-pool=default-dhcp profile=hsprof1 disabled=no
/ip hotspot ip-binding add address=192.168.88.2 type=bypassed comment="Access point"
/ip hotspot walled-garden add dst-host=oswagolink.co.tz
/ip hotspot walled-garden ip add dst-address=69.62.105.119 action=accept
/ip hotspot user profile set default rate-limit=1M/1M
/ip firewall nat add action=masquerade chain=srcnat comment="masquerade hotspot network" src-address=192.168.88.0/24 out-interface-list=WAN

/user group add name=apigroup policy=api,read,write
/user add name=wifiapi group=apigroup address=10.20.0.1 password="${apiPassword}"
/ip service set api address=10.20.0.1/32
/ip service set winbox address=192.168.88.0/24
/ip service disable telnet,ftp,www,ssh,api-ssl

${speedProfiles}
/system script add name=wg-boot policy=read,write,policy,test source={
    /interface wireguard peers disable [find name=peer1]
    :local tries 0
    :while ($tries < 60 && [/ping 8.8.8.8 count=1] = 0) do={
        :delay 5s
        :set tries ($tries + 1)
    }
    :if ($tries >= 60) do={
        :log warning "wg-boot: no internet after 5 minutes, enabling peer1 anyway"
    } else={
        :log info ("wg-boot: internet ready after " . ($tries * 5) . " seconds")
    }
    :delay 90s
    /interface wireguard peers enable [find name=peer1]
    :log info "wg-boot: peer1 enabled"
}
/system script add name=wg-watchdog policy=read,write,policy,test source={
    :global wgFails
    :global wgLastReset
    :if ([:typeof $wgFails] != "num") do={ :set wgFails 0 }
    :if ([:typeof $wgLastReset] != "time") do={ :set wgLastReset 0s }
    :local up [/system resource get uptime]
    :if ($up > 00:08:00) do={
        :if ([/ping 8.8.8.8 count=2] > 0) do={
            :if ([/ping 10.20.0.1 count=3] = 0) do={
                :set wgFails ($wgFails + 1)
                :log warning ("wg-watchdog: VPS not answering, failure " . $wgFails)
                :if ($wgFails >= 3 && ($up - $wgLastReset) > 00:10:00) do={
                    :log warning "wg-watchdog: restarting peer1"
                    /interface wireguard peers disable [find name=peer1]
                    :delay 5s
                    /interface wireguard peers enable [find name=peer1]
                    :set wgLastReset $up
                    :set wgFails 0
                }
            } else={ :set wgFails 0 }
        }
    }
}

# Tell the VPS this router's key. The router accepts it only if the server answers exactly OK.
:local registered false
:for attempt from=1 to=6 do={
    :if (!$registered) do={
        :do {
            :local pk [/interface wireguard get wg-vps public-key]
            :local res [/tool fetch url="https://oswagolink.co.tz/api/provision/register/${token}" check-certificate=yes-without-crl http-method=post http-header-field="Content-Type: application/json" http-data=("{\\"pubkey\\":\\"" . $pk . "\\"}") output=user as-value]
            :if (($res->"data") = "OK") do={ :set registered true }
        } on-error={ :delay 10s }
    }
}
:if (!$registered) do={ :error "REGISTRATION FAILED - check the internet connection, then reset the router to factory settings and run the setup again." }

# Created last: needs device-mode scheduler=yes
/system scheduler add name=wg-boot start-time=startup interval=0 on-event="/system script run wg-boot"
/system scheduler add name=wg-watchdog interval=2m on-event="/system script run wg-watchdog"
:put "SETUP COMPLETE"
`;
    res.setHeader('Content-Type', 'text/plain');
    res.send(script);
  } catch (error) {
    console.error('Bootstrap error:', error.message);
    res.status(500).type('text/plain').send('# Error');
  }
};

// The redirect page the router shows to guests (replaces login.html on the router)
const getLoginPage = async (req, res) => {
  try {
    const { token } = req.params;
    if (!TOKEN_RE.test(token)) return res.status(404).type('text/plain').send('Not found');

    const routerRes = await db.query('SELECT router_token FROM routers WHERE provision_token = $1', [token]);
    const router = routerRes.rows[0];
    if (!router || !TOKEN_RE.test(String(router.router_token))) {
      return res.status(404).type('text/plain').send('Not found');
    }

    const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Redirecting...</title>
</head>
<body>
  <p>Opening Wi-Fi login...</p>
  <script>
    const router = "${router.router_token}";
    const mac = "$(mac)";
    const login = "$(link-login-only)";
    const original = "$(link-orig)";
    const portal =
      "https://oswagolink.co.tz/portal/" +
      "?router=" + encodeURIComponent(router) +
      "&mac=" + encodeURIComponent(mac) +
      "&login=" + encodeURIComponent(login) +
      "&orig=" + encodeURIComponent(original);
    window.location.replace(portal);
  </script>
</body>
</html>`;
    res.type('html').send(html);
  } catch (error) {
    console.error('Login page error:', error.message);
    res.status(500).type('text/plain').send('Error');
  }
};

// The router sends its public key here (POST, JSON body)
const registerRouterKey = async (req, res) => {
  try {
    const { token } = req.params;
    if (!TOKEN_RE.test(token)) return res.status(404).send('Invalid token');

    const pubkey = String((req.body && req.body.pubkey) || '');
    if (!PUBKEY_RE.test(pubkey)) return res.status(400).send('Invalid key');

    const routerRes = await db.query('SELECT * FROM routers WHERE provision_token = $1', [token]);
    const router = routerRes.rows[0];
    if (!router) return res.status(404).send('Invalid token');
    if (router.provisioned_at) return res.status(410).send('Token already used');
    if (!isClientTunnelIp(router.tunnel_ip)) return res.status(400).send('No tunnel address yet');

    // No shell is used, so nothing sent by the router can run as a command
    execFile(
      'flock',
      ['-w', '10', '/var/lock/wg-enroll.lock', 'sudo', '-n', '/usr/local/sbin/wifi-wireguard-add-peer', pubkey, router.tunnel_ip + '/32'],
      (error, stdout, stderr) => {
        if (error) {
          console.error('Enrollment error:', stderr || error.message);
          return res.status(500).send('Failed to add peer');
        }
        // public_key is needed later to remove this peer when the router is deleted
        db.query('UPDATE routers SET provisioned_at = NOW(), public_key = $2 WHERE id = $1', [router.id, pubkey])
          .catch((e) => console.error('provisioned_at update failed:', e.message));
        res.type('text/plain').send('OK');
      }
    );
  } catch (error) {
    console.error('Register error:', error.message);
    res.status(500).send('Error');
  }
};

module.exports = { getBootstrapScript, getLoginPage, registerRouterKey };