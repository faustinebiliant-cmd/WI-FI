const db = require('../config/db');
const { exec } = require('child_process');

// 1. The Router asks for its configuration script
const getBootstrapScript = async (req, res) => {
  try {
    const { token } = req.params;

    // Find the router by its unique provisioning token
    const routerRes = await db.query('SELECT * FROM routers WHERE provision_token = $1', [token]);
    const router = routerRes.rows[0];
    if (!router) return res.status(404).send('# Invalid Token');

    let assignedIp = router.tunnel_ip;
    
    // If this router doesn't have an IP yet, assign the next available one
    if (!assignedIp) {
      const ipRes = await db.query("SELECT tunnel_ip FROM routers WHERE tunnel_ip IS NOT NULL ORDER BY tunnel_ip DESC LIMIT 1");
      if (ipRes.rows.length === 0) {
        assignedIp = "10.20.0.3";
      } else {
        const lastIp = ipRes.rows[0].tunnel_ip;
        const lastOctet = parseInt(lastIp.split('.')[3]);
        assignedIp = `10.20.0.${lastOctet + 1}`;
      }
      await db.query('UPDATE routers SET tunnel_ip = $1 WHERE id = $2', [assignedIp, router.id]);
    }

    // Generate the script on the fly
    const script = `
# ===== OSWAGOLINK ZERO-TOUCH PROVISIONING =====
/ip dns set allow-remote-requests=yes servers=8.8.8.8,1.1.1.1
/ip cloud set update-time=yes
/system ntp client set enabled=yes servers=time.google.com,pool.ntp.org

/interface wireguard add name=wg-vps listen-port=51820
/ip address add address=${assignedIp}/24 interface=wg-vps
/interface wireguard peers add interface=wg-vps name=peer1 public-key="ge0I3cNGfsm5MuItotNBt5KDrSGeg3lhRThsDFc3byY=" endpoint-address=69.62.105.119 endpoint-port=51820 allowed-address=10.20.0.1/32 persistent-keepalive=25s

/ip firewall filter add chain=input action=accept protocol=tcp dst-port=8728 in-interface=wg-vps src-address=10.20.0.1 place-before=0
/ip firewall filter add chain=forward action=drop src-address=192.168.88.0/24 out-interface=wg-vps place-before=0

/ip hotspot profile set [find default=yes] login-by=http-pap
/ip hotspot profile add name=hsprof1 hotspot-address=192.168.88.1 html-directory=flash/hotspot login-by=http-pap
/ip hotspot add name=hotspot1 interface=bridge address-pool=default-dhcp profile=hsprof1 disabled=no
/ip hotspot ip-binding add address=192.168.88.2 type=bypassed
/ip hotspot walled-garden add dst-host=oswagolink.co.tz
/ip hotspot walled-garden ip add dst-address=69.62.105.119 action=accept
/ip firewall nat add action=masquerade chain=srcnat src-address=192.168.88.0/24 out-interface-list=WAN

/user group add name=apigroup policy=api,read,write,policy,test
/user add name=wifiapi group=apigroup address=10.20.0.1 password="AutoGenerated123!"
/ip service set api address=10.20.0.1/32
/ip service disable telnet,ftp,www,ssh,api-ssl

/system script add name=wg-boot policy=read,write,policy,test source={
    /interface wireguard peers disable [find name=peer1]
    :do {
        :local tries 0
        :while ($tries < 60 && [/ping 8.8.8.8 count=1] = 0) do={
            :delay 5s
            :set tries ($tries + 1)
        }
        :delay 90s
    } on-error={ :log warning "wg-boot: wait failed" }
    /interface wireguard peers enable [find name=peer1]
}
/system script add name=wg-watchdog policy=read,write,policy,test source={
    :if ([/system resource get uptime] > 00:08:00) do={
        :if ([/ping 8.8.8.8 count=2] > 0) do={
            :if ([/ping 10.20.0.1 count=3] = 0) do={
                /interface wireguard peers disable [find name=peer1]
                :delay 5s
                /interface wireguard peers enable [find name=peer1]
            }
        }
    }
}
/system scheduler add name=wg-boot start-time=startup interval=0 on-event="/system script run wg-boot"
/system scheduler add name=wg-watchdog interval=2m on-event="/system script run wg-watchdog"

# Register with VPS (Sends the Public Key back)
/tool fetch url="https://oswagolink.co.tz/api/provision/register/${token}?pubkey=\$[/interface wireguard get wg-vps public-key]" keep-result=no
`;
    res.setHeader('Content-Type', 'text/plain');
    res.send(script);
  } catch (error) {
    console.error(error);
    res.status(500).send('# Error');
  }
};

// 2. The Router sends its public key here
const registerRouterKey = async (req, res) => {
  try {
    const { token } = req.params;
    const { pubkey } = req.query;

    if (!pubkey) return res.status(400).send('Missing key');

    const routerRes = await db.query('SELECT * FROM routers WHERE provision_token = $1', [token]);
    const router = routerRes.rows[0];
    if (!router) return res.status(404).send('Invalid token');

    // Call the secure wrapper using flock to prevent concurrent writes
    const command = `flock -w 10 /var/lock/wg-enroll.lock sudo /usr/local/sbin/wifi-wireguard-add-peer "${pubkey}" "${router.tunnel_ip}/32"`;
    
    exec(command, (error, stdout, stderr) => {
      if (error) {
        console.error('Enrollment Error:', stderr);
        return res.status(500).send('Failed to add peer');
      }
      
      // Mark the router as online in the database
      db.query('UPDATE routers SET status = $1 WHERE id = $2', ['online', router.id]);
      res.send('OK');
    });
  } catch (error) {
    console.error(error);
    res.status(500).send('Error');
  }
};

module.exports = { getBootstrapScript, registerRouterKey };