// The redirect page the router shows to customers (replaces login.html on the router)
const getLoginPage = async (req, res) => {
  try {
    const { token } = req.params;
    if (!isValidRouterToken(token)) return res.status(404).type('text/plain').send('Not found');

    const routerRes = await db.query('SELECT router_token FROM routers WHERE provision_token = $1', [token]);
    const router = routerRes.rows[0];
    if (!router || !isValidRouterToken(String(router.router_token))) {
      return res.status(404).type('text/plain').send('Not found');
    }

    const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Redirecting...</title>
</head>
<body>
  <p>Opening Wi-Fi login...</p>
  <script>
    const router = "${router.router_token}";
    const mac = "$(mac)";
    const login = "$(link-login-only)";
    const original = "$(link-orig)";
    const portal =
      "https://oswagolink.co.tz/portal/" +
      "?router=" + encodeURIComponent(router) +
      "&mac=" + encodeURIComponent(mac) +
      "&login=" + encodeURIComponent(login) +
      "&orig=" + encodeURIComponent(original);
    window.location.replace(portal);
  </script>
</body>
</html>`;
    res.type('html').send(html);
  } catch (error) {
    console.error('Login page error:', error.message);
    res.status(500).type('text/plain').send('Error');
  }
};

// The router sends its public key here (POST, JSON body)
const registerRouterKey = async (req, res) => {
  try {
    const { token } = req.params;
    if (!isValidRouterToken(token)) return res.status(404).send('Invalid token');

    const pubkey = String((req.body && req.body.pubkey) || '');
    if (!PUBKEY_RE.test(pubkey)) return res.status(400).send('Invalid key');

    // 10 extra minutes, so a setup started just before the link expired can still finish
    // (the router registers about a minute after it downloaded its setup)
    const routerRes = await db.query(
      `SELECT *, (provision_token_expires_at + INTERVAL '10 minutes' > NOW()) AS token_valid
       FROM routers WHERE provision_token = $1`,
      [token]
    );
    const router = routerRes.rows[0];
    if (!router) return res.status(404).send('Invalid token');
    if (router.provisioned_at) return res.status(410).send('Token already used');
    if (!router.token_valid) return res.status(410).send('Setup link expired');
    if (!isClientTunnelIp(router.tunnel_ip)) return res.status(400).send('No tunnel address yet');

    // No shell is used, so nothing sent by the router can run as a command
    execFile(
      'flock',
      ['-w', '10', '/var/lock/wg-enroll.lock', 'sudo', '-n', '/usr/local/sbin/wifi-wireguard-add-peer', pubkey, router.tunnel_ip + '/32'],
      (error, stdout, stderr) => {
        if (error) {
          console.error('Enrollment error:', stderr || error.message);
          return res.status(500).send('Failed to add peer');
        }
        // public_key is needed later to remove this peer when the router is deleted
        db.query('UPDATE routers SET provisioned_at = NOW(), public_key = $2 WHERE id = $1', [router.id, pubkey])
          .catch((e) => console.error('provisioned_at update failed:', e.message));
        res.type('text/plain').send('OK');
      }
    );
  } catch (error) {
    console.error('Register error:', error.message);
    res.status(500).send('Error');
  }
};

module.exports = { getBootstrapScript, getLoginPage, registerRouterKey };