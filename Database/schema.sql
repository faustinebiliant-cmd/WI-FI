-- ============================================================
-- OSWAGOTech WiFi - Complete Database Schema
-- ============================================================

-- 1. platform_admins (You, the SaaS owner)
CREATE TABLE public.platform_admins (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email varchar(255) UNIQUE NOT NULL,
    password_hash varchar(255) NOT NULL,
    full_name varchar(255) NOT NULL,
    is_active boolean DEFAULT true NOT NULL,
    last_login_at timestamptz,
    created_at timestamptz DEFAULT now() NOT NULL
);

-- 2. tenants (The Hotel / Guest House)
CREATE TABLE public.tenants (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    business_name varchar(255) NOT NULL,
    owner_name varchar(255) NOT NULL,
    owner_phone varchar(50),
    owner_email varchar(255),
    subscription_status varchar(50) DEFAULT 'trial',
    trial_ends_at date,
    monthly_fee_tzs numeric,
    payment_mode varchar(50) DEFAULT 'manual',
    notes text,
    logo_url text,
    created_at timestamptz DEFAULT now() NOT NULL
);

-- 3. tenant_users (The Hotel Owner's Login)
CREATE TABLE public.tenant_users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid REFERENCES public.tenants(id) ON DELETE CASCADE NOT NULL,
    email varchar(255) UNIQUE NOT NULL,
    password_hash varchar(255) NOT NULL,
    full_name varchar(255) NOT NULL,
    role varchar(50) DEFAULT 'owner',
    is_active boolean DEFAULT true NOT NULL,
    last_login_at timestamptz,
    created_at timestamptz DEFAULT now() NOT NULL
);

-- 4. routers (The MikroTik Hardware)
CREATE TABLE public.routers (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid REFERENCES public.tenants(id) ON DELETE CASCADE NOT NULL,
    name varchar(255) NOT NULL,
    location_label varchar(255),
    ip_address varchar(50),
    api_port integer DEFAULT 8728,
    api_username varchar(100),
    api_password_encrypted text,
    router_token varchar(255) UNIQUE NOT NULL,
    status varchar(50) DEFAULT 'offline',
    last_seen_at timestamptz,
    created_at timestamptz DEFAULT now() NOT NULL
);

-- 5. packages (WiFi Bundles created by Tenants)
CREATE TABLE public.packages (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid REFERENCES public.tenants(id) ON DELETE CASCADE NOT NULL,
    name varchar(255) NOT NULL,
    price_tzs numeric NOT NULL,
    duration_minutes integer NOT NULL,
    speed_down_kbps integer NOT NULL,
    speed_up_kbps integer NOT NULL,
    is_active boolean DEFAULT true NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL
);

-- 6. payments (Pre-created for future gateway integration)
CREATE TABLE public.payments (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid REFERENCES public.tenants(id) ON DELETE CASCADE NOT NULL,
    router_id uuid REFERENCES public.routers(id) ON DELETE SET NULL,
    package_id uuid REFERENCES public.packages(id) ON DELETE SET NULL,
    amount_tzs numeric NOT NULL,
    guest_phone varchar(50),
    gateway_reference varchar(255) UNIQUE,
    status varchar(50) DEFAULT 'pending',
    created_at timestamptz DEFAULT now() NOT NULL
);

-- 7. vouchers (The Codes generated by Tenants)
-- FIXED: package_id allows null and cascades on delete
CREATE TABLE public.vouchers (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid REFERENCES public.tenants(id) ON DELETE CASCADE NOT NULL,
    package_id uuid REFERENCES public.packages(id) ON DELETE CASCADE,
    code varchar(20) NOT NULL,
    status varchar(50) DEFAULT 'unused',
    used_at timestamptz,
    expires_at timestamptz,
    created_by uuid REFERENCES public.tenant_users(id) ON DELETE SET NULL,
    payment_id uuid REFERENCES public.payments(id) ON DELETE SET NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    UNIQUE (tenant_id, code)
);

-- 8. sessions (Live and Past Guest Connections)
CREATE TABLE public.sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id uuid REFERENCES public.tenants(id) ON DELETE CASCADE NOT NULL,
    router_id uuid REFERENCES public.routers(id) ON DELETE CASCADE NOT NULL,
    voucher_id uuid REFERENCES public.vouchers(id) ON DELETE SET NULL,
    mac_address varchar(50) NOT NULL,
    ip_address varchar(50),
    started_at timestamptz DEFAULT now() NOT NULL,
    ended_at timestamptz,
    data_used_mb numeric DEFAULT 0,
    disconnect_reason varchar(100)
);

-- 9. impersonation_sessions (Admin acting as Tenant)
CREATE TABLE public.impersonation_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    admin_id uuid REFERENCES public.platform_admins(id) ON DELETE CASCADE NOT NULL,
    admin_email varchar(255) NOT NULL,
    tenant_id uuid REFERENCES public.tenants(id) ON DELETE CASCADE NOT NULL,
    tenant_user_id uuid REFERENCES public.tenant_users(id) ON DELETE CASCADE NOT NULL,
    reason text NOT NULL,
    token_id uuid UNIQUE NOT NULL,
    started_at timestamptz DEFAULT now() NOT NULL,
    expires_at timestamptz NOT NULL,
    ended_at timestamptz,
    ended_by varchar(50),
    ip_address varchar(50)
);

-- 10. platform_audit_logs (Every action you take)
CREATE TABLE public.platform_audit_logs (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    admin_id uuid REFERENCES public.platform_admins(id) ON DELETE SET NULL,
    admin_email varchar(255),
    action varchar(100) NOT NULL,
    target_type varchar(50),
    target_id uuid,
    target_label varchar(255),
    details jsonb,
    created_at timestamptz DEFAULT now() NOT NULL
);

-- ==========================================
-- ATOMIC FUNCTIONS (RPCs)
-- ==========================================

-- Function to safely create a Tenant and their first Login
CREATE OR REPLACE FUNCTION create_tenant_with_owner(
    p_business_name varchar,
    p_owner_name varchar,
    p_owner_email varchar,
    p_owner_phone varchar,
    p_owner_password_hash varchar,
    p_monthly_fee numeric
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_tenant_id uuid;
    v_user_id uuid;
BEGIN
    INSERT INTO public.tenants (
        business_name, owner_name, owner_email, owner_phone, monthly_fee_tzs, subscription_status
    ) VALUES (
        p_business_name, p_owner_name, p_owner_email, p_owner_phone, p_monthly_fee, 'trial'
    ) RETURNING id INTO v_tenant_id;

    INSERT INTO public.tenant_users (
        tenant_id, email, full_name, password_hash, role
    ) VALUES (
        v_tenant_id, p_owner_email, p_owner_name, p_owner_password_hash, 'owner'
    ) RETURNING id INTO v_user_id;

    RETURN jsonb_build_object(
        'tenant_id', v_tenant_id,
        'user_id', v_user_id
    );
END;
$$;

-- ==========================================
-- INDEXES FOR PERFORMANCE & PAGINATION
-- ==========================================
-- Base indexes (tenant scoping)
CREATE INDEX idx_tenant_users_tenant ON public.tenant_users(tenant_id);
CREATE INDEX idx_routers_tenant ON public.routers(tenant_id);
CREATE INDEX idx_packages_tenant ON public.packages(tenant_id);
CREATE INDEX idx_vouchers_tenant ON public.vouchers(tenant_id);
CREATE INDEX idx_sessions_tenant ON public.sessions(tenant_id);

-- Lookup indexes
CREATE INDEX idx_vouchers_code ON public.vouchers(tenant_id, code);
CREATE INDEX idx_sessions_active ON public.sessions(tenant_id, ended_at);

-- Sorting indexes for Pagination (Newest first)
CREATE INDEX idx_packages_tenant_created ON public.packages(tenant_id, created_at DESC);
CREATE INDEX idx_vouchers_tenant_created ON public.vouchers(tenant_id, created_at DESC);
CREATE INDEX idx_sessions_tenant_started ON public.sessions(tenant_id, started_at DESC);
CREATE INDEX idx_audit_created ON public.platform_audit_logs(created_at DESC);